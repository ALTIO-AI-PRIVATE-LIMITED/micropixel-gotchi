"""Bake the Devcon 8 India logo and the tagline into src/brand_data.hpp.

Each image becomes a small RGBA palette (RGB565 + 8-bit alpha, index 0 is
transparent) and per-row run-length data, so a Gotchi only decodes the rows
that fall on its own tile. Needs Pillow:

    python3 tools/gen_brand.py
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "art" / "dc8-logo.png"
OUT = ROOT / "src" / "brand_data.hpp"

LOGO_WIDTH = 762  # 1.5x the 508 px source; spans the three wall columns.
TAGLINE = "MUMBAI  •  3–6 NOV 2026"
TAGLINE_FONTS = [
    "/System/Library/Fonts/Supplemental/DIN Alternate Bold.ttf",
    "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
]
TAGLINE_SIZE = 46
COLORS = 200


def rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def encode(name: str, image: Image.Image) -> str:
    image = image.convert("RGBA")
    width, height = image.size
    # Clear faint pixels so they become the transparent index 0.
    pixels = [(0, 0, 0, 0) if p[3] < 16 else p for p in list(image.getdata())]
    image.putdata(pixels)
    quant = image.quantize(colors=COLORS, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    base = quant.getpalette(rawmode="RGBA")
    px = quant.load()
    remap: dict[int, int] = {}
    palette: list[tuple[int, int]] = [(0, 0)]
    rows: list[list[int]] = []
    for y in range(height):
        row: list[int] = []
        run_index, run_length = -1, 0
        for x in range(width):
            q = px[x, y]
            index = remap.get(q)
            if index is None:
                r, g, b, a = base[q * 4 : q * 4 + 4]
                if a < 16:
                    index = 0
                else:
                    palette.append((rgb565(r, g, b), 255 if a > 240 else a))
                    index = len(palette) - 1
                remap[q] = index
            if index == run_index and run_length < 255:
                run_length += 1
            else:
                if run_length:
                    row += [run_index, run_length]
                run_index, run_length = index, 1
        row += [run_index, run_length]
        rows.append(row)
    data: list[int] = []
    offsets: list[int] = []
    for row in rows:
        offsets.append(len(data))
        data += row
    offsets.append(len(data))

    def block(values: list[int], per_line: int = 24) -> str:
        lines = []
        for start in range(0, len(values), per_line):
            lines.append("    " + ", ".join(str(v) for v in values[start : start + per_line]) + ",")
        return "\n".join(lines)

    upper = name.upper()
    return (
        f"inline constexpr int32_t k{name}Width = {width};\n"
        f"inline constexpr int32_t k{name}Height = {height};\n"
        f"inline constexpr uint16_t k{name}Color[{len(palette)}] = {{\n{block([p[0] for p in palette])}\n}};\n"
        f"inline constexpr uint8_t k{name}Alpha[{len(palette)}] = {{\n{block([p[1] for p in palette])}\n}};\n"
        f"inline constexpr uint32_t k{name}RowOffset[{len(offsets)}] = {{\n{block(offsets, 16)}\n}};\n"
        f"// {upper}: pairs of (palette index, run length) per row.\n"
        f"inline constexpr uint8_t k{name}Runs[{len(data)}] = {{\n{block(data, 32)}\n}};\n"
    )


def tagline() -> Image.Image:
    font = None
    for path in TAGLINE_FONTS:
        if Path(path).exists():
            font = ImageFont.truetype(path, TAGLINE_SIZE)
            break
    if font is None:
        raise SystemExit("no tagline font found")
    box = font.getbbox(TAGLINE)
    width, height = box[2] - box[0] + 8, box[3] - box[1] + 8
    image = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    ImageDraw.Draw(image).text((4 - box[0], 4 - box[1]), TAGLINE, font=font, fill=(255, 244, 228, 255))
    return image


def main() -> None:
    logo = Image.open(LOGO).convert("RGBA")
    scale = LOGO_WIDTH / logo.width
    logo = logo.resize((LOGO_WIDTH, round(logo.height * scale)), Image.Resampling.LANCZOS)
    text = (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by tools/gen_brand.py from art/dc8-logo.png. Do not edit.\n"
        "// Devcon logo artwork belongs to the Ethereum Foundation (devcon.org).\n"
        "#pragma once\n\n#include <stdint.h>\n\nnamespace devcon_wall::brand {\n\n"
        + encode("Logo", logo)
        + "\n"
        + encode("Tagline", tagline())
        + "\n}  // namespace devcon_wall::brand\n"
    )
    OUT.write_text(text)
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB source)")


if __name__ == "__main__":
    main()
