#!/usr/bin/env python3
"""Render printable ASCII from a TTF into the 1-bit fonts in main/font.h.

    python3 tools/make_font.py /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf > main/font.h
"""
import sys

from PIL import Image, ImageDraw, ImageFont

SIZES = {"small": 20, "large": 40}
FIRST, LAST = 32, 126


def render(path, name, px):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    widths, offsets, data = [], [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        width = max(1, int(round(font.getlength(ch))))
        img = Image.new("1", (width, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
        offsets.append(len(data))
        widths.append(width)
        row_bytes = (width + 7) // 8
        for y in range(height):
            for bx in range(row_bytes):
                byte = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < width and img.getpixel((x, y)):
                        byte |= 0x80 >> bit
                data.append(byte)
    out = [f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append(f"static const uint16_t {name}_offsets[] = {{{', '.join(map(str, offsets))}}};")
    out.append(f"static const uint8_t {name}_widths[] = {{{', '.join(map(str, widths))}}};")
    out.append(f"static const font_t font_{name} = {{{height}, {name}_bits, {name}_offsets, {name}_widths}};")
    return "\n".join(out)


def main():
    path = sys.argv[1]
    print("// Generated by tools/make_font.py from " + path.rsplit("/", 1)[-1] + ". Do not edit.")
    print("#pragma once\n\n#include <stdint.h>\n")
    print("typedef struct {\n    uint8_t height;\n    const uint8_t *bits;\n"
          "    const uint16_t *offsets;\n    const uint8_t *widths;\n} font_t;\n")
    print(f"#define FONT_FIRST_CHAR {FIRST}\n#define FONT_LAST_CHAR {LAST}\n")
    for name, px in SIZES.items():
        print(render(path, name, px))
        print()


if __name__ == "__main__":
    main()
